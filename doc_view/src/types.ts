/**
 * Format categories corresponding to user-configurable settings toggles.
 */
export type FormatCategory =
  | 'pdf'
  | 'docs'
  | 'books'
  | 'text'
  | 'web'
  | 'image'
  | 'archive'

/**
 * Concrete supported document formats.
 */
export type DocumentFormat =
  | 'pdf'
  | 'image'
  | 'web'
  | 'csv'
  | 'json'
  | 'ipynb'
  | 'doc'
  | 'docx'
  | 'xlsx'
  | 'pptx'
  | 'odf'
  | 'rtf'
  | 'eml'
  | 'epub'
  | 'fb2'
  | 'archive'
  | 'comic'
  | 'text'

/**
 * High-level viewer routing kind.
 */
export type ViewerKind = 'pdf' | 'image' | 'web' | 'text'

/**
 * Metadata resolved from an incoming openForView call.
 */
export interface ResolvedFile {
  /** Absolute path on device filesystem */
  path: string
  /** Human-readable filename (e.g. "report.docx") */
  name: string
  /** MIME type string (if available) */
  mime: string
  /** File size in bytes */
  size: number
  /** Identified document format */
  format: DocumentFormat
  /** Associated format settings category */
  category: FormatCategory
  /** File extension without dot in lowercase */
  extension: string
  /** High-level rendering engine to route to */
  kind: ViewerKind
}

/**
 * Theme configuration for document rendering.
 */
export interface ViewerTheme {
  name: string
  bg: number
  fg: number
  sub: number
  bar: number
  btn: number
  pill: number
  hit?: number
  cur?: number
  cssBg?: string
  cssFg?: string
  cssAlt?: string
}

/**
 * User-configurable plugin settings.
 */
export interface DocViewerSettings {
  // Format toggles
  pdf: boolean
  docs: boolean
  books: boolean
  text: boolean
  web: boolean
  image: boolean
  archive: boolean

  // Viewer preferences
  invert: boolean
  fitwidth: boolean
  remember: boolean
  volume: boolean
  keepon: boolean
  wrap: boolean
  prettyjson: boolean
  csv_table: boolean

  // Text appearance
  theme: number
  font: number
  text_size: number

  // Localization
  language: LanguageSetting

  // Reading history
  history?: string
}

export type LanguageSetting = 'system' | 'en' | 'ru'

/**
 * Cancellation token for cooperative asynchronous background processing.
 */
export interface CancellationToken {
  isCancelled: boolean
  cancel: () => void
}

/**
 * A paginated document model for text rendering.
 */
export interface PaginatedDoc {
  pages: string[]
  font: number
  wrap: boolean
  encoding?: string
  note?: string
}

/**
 * Report generated by active content inspection of HTML/SVG.
 */
export interface ActiveContentReport {
  hasActiveContent: boolean
  hasScriptTags: boolean
  hasEventHandlers: boolean
  hasJavascriptUrls: boolean
  hasSvgActiveContent: boolean
  hasEmbeddedObjects: boolean
  details: string[]
}

/**
 * User action chosen in the JavaScript detected confirmation dialog.
 */
export type JsDecision = 'open_without_js' | 'enable_js' | 'cancel'

/**
 * Result of converting rich documents (.docx, .odt, .rtf) to HTML.
 */
export interface DocumentHtmlResult {
  html: string
  title?: string
  pageCount?: number
}


